import { readFile, mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const root = new URL("../../docs/pico8-agent/", import.meta.url);
const read = (path) => readFile(new URL(path, root), "utf8");
const hash = (text) => createHash("sha256").update(text).digest("hex");
const manifest = JSON.parse(await read("manifest.json"));
const palette = JSON.parse(await read("palette.json"));
const validation = JSON.parse(await read("validation-results.json"));
const references = {};
for (const item of manifest.references) {
  if (references[item.id]) throw new Error(`Duplicate reference ${item.id}`);
  let content = await read(item.file);
  if (item.heading) {
    const marker = `## ${item.heading}\n`;
    if (content.split(marker).length !== 2)
      throw new Error(`Invalid heading ${item.id}`);
    content = marker + content.split(marker)[1].split("\n## ")[0];
  }
  if (item.id.startsWith("recipe/")) {
    const receipt = validation.checks.find(
      (c) =>
        c.name ===
        item.file.split("/").at(-1).replace(".lua", "") +
          ": original Lua and exported cart",
    );
    if (!receipt?.passed || receipt.sourceSha256 !== hash(content))
      throw new Error(`Unverified recipe ${item.id}`);
  }
  if (
    /[\u3400-\u9fff]/u.test(content) ||
    /\/Users\/|\]\([^)]*\.md\)/u.test(content)
  )
    throw new Error(`Unprocessed model content ${item.id}`);
  references[item.id] = {
    id: item.id,
    title: item.title,
    sha256: hash(content),
    content,
  };
}
const sections = {};
for (const [key, file] of Object.entries(manifest.sections))
  sections[key] = await read(file);
sections.pico8_palette =
  "Default colors: numeric Lua ID / pixel character / English name / RGB\n" +
  palette.slots
    .map((s) => {
      const c = palette.colors.find(
        (c) => c.displayCode === s.defaultDisplayCode,
      );
      return `${s.index} / ${s.character} / ${c.nameEn} / ${c.rgb}`;
    })
    .join("\n") +
  '\nExtended display colors: read_reference({"id":"palette/full"}).';
sections.pico8_references =
  'Use read_reference({"id":"..."}) to retrieve a complete guide or executable recipe. Available IDs:\n' +
  Object.values(references)
    .map((r) => `${r.id}: ${r.title}`)
    .join("\n");
const version =
  "pico8-en-v1-" + hash(JSON.stringify({ sections, references })).slice(0, 16);
for (const r of Object.values(references)) {
  r.packVersion = version;
  r.outputText = `Reference: ${r.id}\nTitle: ${r.title}\nVersion: ${version}\nSHA-256: ${r.sha256}\n\n${r.content}`;
  if (
    Buffer.byteLength(r.outputText) > 16384 ||
    r.outputText.split("\n").length > 256
  )
    throw new Error(`Reference too large ${r.id}`);
}
for (const text of Object.values(sections))
  if (/[\u3400-\u9fff]/u.test(text) || text.includes("/Users/"))
    throw new Error("Invalid section language/path");
const output = new URL("../src/generated/pico8-knowledge.js", import.meta.url);
await mkdir(new URL(".", output), { recursive: true });
await writeFile(
  output,
  `// Generated by prepare-knowledge.mjs; edit docs/pico8-agent instead.\nexport default ${JSON.stringify({ version, sections, references })};\n`,
);
// Share the knowledge pack's English labels with the runtime encoder, without
// importing the entire reference library into the game/player module.
await writeFile(
  new URL("pico8-palette.js", output),
  `// Generated by prepare-knowledge.mjs from palette.json.\nexport default ${JSON.stringify(palette.colors.map(({ displayCode, nameEn, rgb }) => ({ displayCode, name: nameEn, rgb })))};\n`,
);
console.log(
  `Prepared ${version}: ${Object.keys(references).length} references`,
);
