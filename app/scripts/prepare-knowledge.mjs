import { readFile, mkdir, writeFile, rm } from "node:fs/promises";
import { createHash } from "node:crypto";
const root = new URL("../../docs/pico8-agent/", import.meta.url);
const read = (path) => readFile(new URL(path, root), "utf8");
const hash = (text) => createHash("sha256").update(text).digest("hex");
const manifest = JSON.parse(await read("manifest.json"));
const palette = JSON.parse(await read("palette.json"));
// Fixed, repository-owned skills use a deliberately narrow frontmatter format.
// This publishes metadata, not a general filesystem/package discovery service.
const skills = [];
const skillNames = new Set();
const fileTexts = {};
for (const file of manifest.skills ?? []) {
  const text = await read(file);
  const match = text.match(
    /^---\nname: ([a-z0-9]+(?:-[a-z0-9]+)*)\ndescription: ([^\n]+)\n---\n/,
  );
  if (
    !match ||
    match[1].length > 64 ||
    match[2].length > 1024 ||
    file !== `skills/${match[1]}/SKILL.md` ||
    skillNames.has(match[1])
  )
    throw new Error(`Invalid skill metadata: ${file}`);
  if (/[\u3400-\u9fff]/u.test(text) || text.includes("/Users/"))
    throw new Error(`Invalid skill content: ${file}`);
  skillNames.add(match[1]);
  skills.push({ name: match[1], description: match[2], file });
  fileTexts[file] = text;
}
const validations = new Map();
for (const {
  file,
  validation: receiptFile = "validation-results.json",
} of manifest.references) {
  if (Object.hasOwn(fileTexts, file))
    throw new Error(`Duplicate reference ${file}`);
  const content = await read(file);
  if (file.endsWith(".lua")) {
    if (!validations.has(receiptFile))
      validations.set(receiptFile, JSON.parse(await read(receiptFile)));
    const validation = validations.get(receiptFile);
    const receipt = validation.checks.find(
      (c) =>
        c.name ===
        file.split("/").at(-1).replace(".lua", "") +
          ": original Lua and exported cart",
    );
    if (!receipt?.passed || receipt.sourceSha256 !== hash(content))
      throw new Error(`Unverified recipe ${file}`);
  }
  if (
    /[\u3400-\u9fff]/u.test(content) ||
    /\/Users\/|\]\([^)]*\.md\)/u.test(content)
  )
    throw new Error(`Unprocessed model content ${file}`);
  fileTexts[file] = content;
}
for (const file of Object.values(manifest.sections)) {
  const text = await read(file);
  if (/[\u3400-\u9fff]/u.test(text) || text.includes("/Users/"))
    throw new Error(`Invalid section language/path: ${file}`);
  fileTexts[file] = text;
}
fileTexts["PALETTE_DEFAULT.md"] =
  "Base palette in slot order 0–f: " +
  palette.slots
    .map(
      (s) =>
        palette.colors.find((c) => c.displayCode === s.defaultDisplayCode)
          .nameEn,
    )
    .join(", ") +
  ". Use numeric Lua IDs. RGB and extended colors: /extensions/pico8/PALETTE.md.";
const output = new URL("../src/generated/pico8-files.js", import.meta.url);
await mkdir(new URL(".", output), { recursive: true });
// Share the knowledge pack's English labels with the runtime encoder, without
// importing the entire reference library into the game/player module.
await writeFile(
  new URL("pico8-palette.js", output),
  `// Generated by prepare-knowledge.mjs from palette.json.\nexport default ${JSON.stringify(palette.colors.map(({ displayCode, nameEn, rgb }) => ({ displayCode, name: nameEn, rgb })))};\n`,
);
// Publish original model-facing files as versioned static assets. The browser imports only metadata.
const files = {};
fileTexts["SKILLS.md"] =
  "# Skills\n" +
  skills
    .map(
      (s) =>
        `- ${s.name}: ${s.description}\n  Path: /extensions/pico8/${s.file}`,
    )
    .join("\n");
for (const [file, text] of Object.entries(fileTexts)) {
  for (const [path] of text.matchAll(
    /\/extensions\/pico8\/[A-Za-z0-9_./-]+\.(?:md|lua)/g,
  ))
    if (!Object.hasOwn(fileTexts, path.slice("/extensions/pico8/".length)))
      throw new Error(`Unknown documentation link in ${file}: ${path}`);
  files[file] = { sha256: hash(text), size: Buffer.byteLength(text) };
}
const fileVersion =
  "pico8-files-v1-" + hash(JSON.stringify(files)).slice(0, 16);
await rm(new URL("../public/extensions/pico8/", import.meta.url), {
  recursive: true,
  force: true,
});
const publicRoot = new URL(
  `../public/extensions/pico8/${fileVersion}/`,
  import.meta.url,
);
for (const [file, text] of Object.entries(fileTexts)) {
  const target = new URL(file, publicRoot);
  await mkdir(new URL(".", target), { recursive: true });
  await writeFile(target, text);
}
const fileSections = {
  ...manifest.sections,
  pico8_palette: "PALETTE_DEFAULT.md",
  pico8_skills: "SKILLS.md",
};
await writeFile(
  new URL("pico8-files.js", output),
  `// Generated metadata only; document bodies remain static files.\nexport default ${JSON.stringify({ version: fileVersion, files, sections: fileSections })};\n`,
);
console.log(
  `Published ${Object.keys(files).length} documentation files: ${fileVersion}`,
);
