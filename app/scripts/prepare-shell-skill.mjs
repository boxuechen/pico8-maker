// Bundle the shell flow's pico8 skill (src/pico8/shell/skill/) into a module, so
// the browser and Node tests get the same texts without a runtime fetch.
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
const root = new URL("../src/pico8/shell/skill/", import.meta.url);
const files = {};
async function walk(dir) {
  for (const entry of await readdir(new URL(dir, root), { withFileTypes: true })) {
    const path = dir + entry.name;
    if (entry.isDirectory()) await walk(`${path}/`);
    else if (/\.(md|lua)$/.test(entry.name)) files[path] = await readFile(new URL(path, root), "utf8");
  }
}
await walk("");
if (!files["SKILL.md"]) throw new Error("shell skill: SKILL.md is missing");
const out = new URL("../src/generated/shell-skill.js", import.meta.url);
await mkdir(new URL(".", out), { recursive: true });
const sorted = Object.fromEntries(Object.entries(files).sort(([a], [b]) => a.localeCompare(b)));
await writeFile(out, `// Generated by scripts/prepare-shell-skill.mjs from src/pico8/shell/skill/.\nexport default ${JSON.stringify(sorted, null, 1)};\n`);
console.log(`shell skill: ${Object.keys(sorted).length} files`);
