const dictionaries = { en, zh };

function detect() {
  try {
    const saved = globalThis.localStorage?.getItem(KEY);
    if (languages.includes(saved)) return saved;
  } catch {
    // Storage may be blocked; fall back to the browser language.
  }
  return /^zh\b/i.test(globalThis.navigator?.language ?? "") &&
    globalThis.document
    ? "zh"
    : "en";
}

let current = detect();
const listeners = new Set();

function apply() {
  const doc = globalThis.document;
  if (!doc) return;
  doc.documentElement.lang = current === "zh" ? "zh-CN" : "en";
  doc.title = dictionaries[current].docTitle;
}
apply();

export const getLang = () => current;
export function setLang(lang) {
  if (!languages.includes(lang) || lang === current) return;
  current = lang;
  try {
    globalThis.localStorage?.setItem(KEY, lang);
  } catch {
    // The choice still applies to this tab.
  }
  apply();
  for (const listener of listeners) listener();
}

/** Translate a key; function entries receive `vars`. Unknown keys fall back to English. */
export function t(key, vars) {
  const value = dictionaries[current][key] ?? en[key];
  if (value === undefined) return key;
  return typeof value === "function" ? value(vars ?? {}) : value;
}

const subscribe = (listener) => {
  listeners.add(listener);
  return () => listeners.delete(listener);
};
/** Subscribe a component to language changes. */
export function useLang() {
  const lang = useSyncExternalStore(subscribe, getLang, getLang);
  return { lang, t, setLang };
}
